log = get_logger(__name__)

THUMBNAIL_NAME = "thumbnail.png"


def render_thumbnail(mesh: o3d.geometry.TriangleMesh, path: Path, cfg: dict) -> Path | None:
    """Honest placeholder-quality 3D render of the web mesh. None on any failure."""
    try:
        import matplotlib

        matplotlib.use("Agg")  # backend must be set before pyplot is imported
        import matplotlib.pyplot as plt

        vertices = np.asarray(mesh.vertices, dtype=float)
        triangles = np.asarray(mesh.triangles, dtype=int)
        if len(vertices) == 0 or len(triangles) == 0:
            raise ValueError("mesh has no geometry to render")

        size = cfg_get(cfg, "export.thumbnail_size", [800, 600]) or [800, 600]
        width, height = int(size[0]), int(size[1])
        dpi = 100
        fig = plt.figure(figsize=(width / dpi, height / dpi), dpi=dpi)
        try:
            ax = fig.add_subplot(projection="3d")
            ax.plot_trisurf(
                vertices[:, 0], vertices[:, 1], vertices[:, 2],
                triangles=triangles,
                color="#7fa8bf", edgecolor="none", linewidth=0.0,
                antialiased=True, shade=True,
            )
            # Box aspect proportional to the data spans keeps metres equal on
            # every axis, so the object is not stretched to fill the cube.
            spans = np.maximum(vertices.max(axis=0) - vertices.min(axis=0), 1e-6)
            ax.set_box_aspect(tuple(float(s) for s in spans))
            ax.view_init(elev=22, azim=-60)
            ax.set_axis_off()
            fig.subplots_adjust(left=0, right=1, bottom=0, top=1)
            fig.savefig(path, dpi=dpi)
        finally:
            plt.close(fig)
        return Path(path)
    except Exception as exc:
        log.warning("Thumbnail render failed (%s); continuing without %s", exc, THUMBNAIL_NAME)
        return None


def _viewer_snippet(name: str, glb_name: str, processed_at: str) -> str:
    safe_name = html.escape(name, quote=True)
    safe_glb = html.escape(glb_name, quote=True)
    return f"""<!--
  Aura Scan viewer snippet: {safe_name}
  Generated by aura-scan-pipeline v{__version__} ({processed_at}).

  This is a fragment, not a full page. The host page must load model-viewer
  itself; vendor model-viewer.min.js locally for offline-first use, e.g.

      <script type="module" src="/vendor/model-viewer.min.js"></script>

  Serve {safe_glb}, {THUMBNAIL_NAME} and metadata.json alongside the page,
  then paste the element below where the model should appear.
-->
<model-viewer
  src="{safe_glb}"
  poster="{THUMBNAIL_NAME}"
  alt="{safe_name}"
  camera-controls
  auto-rotate
  ar
  ar-modes="webxr scene-viewer quick-look"
  shadow-intensity="1"
  style="width: 100%; max-width: 720px; height: 480px;"
></model-viewer>
"""


def export_web(project: ScanProject, meta: dict, lods: LodSet,
               exports_dir: Path, cfg: dict) -> dict[str, str]:
    exports_dir = ensure_dir(Path(exports_dir))
    files: dict[str, str] = {}

    if render_thumbnail(lods.lod1, exports_dir / THUMBNAIL_NAME, cfg) is not None:
        files["thumbnail"] = THUMBNAIL_NAME

    geometry_files = meta.get("geometry_files") or {}
    basename = project.name.replace(" ", "-").lower()
    glb_name = geometry_files.get("lod1_glb") or f"{basename}_lod1.glb"

    place_id = (meta.get("links") or {}).get("places_link_id")
    if not place_id:
        log.info(
            "links.places_link_id is not set in the manifest; places-entry.json "
            "keeps placeId null until an events engine place id is chosen"
        )

    # The record to attach when the events engine grows a models field on
    # places; places are keyed by id slugs like public-point-lookout-skate-park.
    places_entry = {
        "placeId": place_id,
        "model": {
            "glb": glb_name,
            "poster": THUMBNAIL_NAME,
            "metadata": "metadata.json",
            "dimensions_m": meta.get("dimensions"),
            "capturedAt": meta.get("captured_at"),
        },
        "sensoriumEvidence": meta.get("sensorium_evidence"),
    }
    entry_path = exports_dir / "places-entry.json"
    with open(entry_path, "w", encoding="utf-8") as fh:
        json.dump(np_to_list(places_entry), fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    files["places_entry"] = entry_path.name

    snippet_path = exports_dir / "viewer-snippet.html"
    snippet_path.write_text(
        _viewer_snippet(project.name, glb_name, str(meta.get("processed_at") or "")),
        encoding="utf-8",
    )
    files["viewer_snippet"] = snippet_path.name

    log.info("Web bundle written: %s", ", ".join(sorted(files.values())))
    return files
